/**
 * SPEC-055-iter-2 · AC-03/AC-05 — botón «Workaround permisos micrófono».
 * Visibilidad: solo con el micrófono en denegación dura (denied/restricted);
 * con permiso pendiente (not-determined o snapshot null) no hay entrada TCC
 * que resetear y el botón no se muestra. El comando lanzado en Terminal
 * resetea Microphone Y ScreenCapture de com.maurya.app, y el diálogo de
 * instrucciones (relanzar la app e iniciar una grabación) menciona ambos
 * permisos, con variante de fallback si Terminal no se pudo abrir.
 * Frontera de mocking: permissionsService (resetMicrophonePermission).
 * Generated by QA Dev agent.
 */
import { render, screen } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { beforeEach, describe, expect, it, vi } from 'vitest'
import { MicWorkaroundButton } from '@/components/recording/MicWorkaroundButton'
import { resetMicrophonePermission } from '@/services/permissionsService'
import type { PermissionsSnapshot } from '@/types/audio'

vi.mock('@/services/permissionsService', () => ({
  resetMicrophonePermission: vi.fn()
}))

const GRANTED: PermissionsSnapshot = { microphone: 'granted', systemAudio: 'granted' }
const PENDING: PermissionsSnapshot = {
  microphone: 'not-determined',
  systemAudio: 'not-determined'
}
const MIC_DENIED: PermissionsSnapshot = { microphone: 'denied', systemAudio: 'granted' }
const MIC_RESTRICTED: PermissionsSnapshot = { microphone: 'restricted', systemAudio: 'granted' }

const RESET_BOTH = /tccutil reset Microphone com\.maurya\.app && tccutil reset ScreenCapture com\.maurya\.app/

beforeEach(() => {
  vi.clearAllMocks()
  vi.mocked(resetMicrophonePermission).mockResolvedValue(true)
})

describe('MicWorkaroundButton', () => {
  // SPEC-055-iter-2 · AC-01/AC-06: sin denegación dura no hay workaround
  it('hides the button when the microphone permission is granted or still pending', () => {
    for (const permissions of [GRANTED, PENDING, null]) {
      const { unmount } = render(<MicWorkaroundButton permissions={permissions} />)
      expect(screen.queryByTestId('mic-workaround-button')).not.toBeInTheDocument()
      unmount()
    }
  })

  // SPEC-055-iter-2 · AC-03
  it('shows the button when the microphone permission is denied or restricted', () => {
    const { unmount } = render(<MicWorkaroundButton permissions={MIC_DENIED} />)
    expect(screen.getByTestId('mic-workaround-button')).toHaveTextContent(
      'Workaround permisos micrófono'
    )
    unmount()

    render(<MicWorkaroundButton permissions={MIC_RESTRICTED} />)
    expect(screen.getByTestId('mic-workaround-button')).toBeInTheDocument()
  })

  // SPEC-055-iter-2 · AC-05
  it('launches the Microphone and ScreenCapture reset in Terminal and shows the relaunch-and-record instructions', async () => {
    const user = userEvent.setup()
    render(<MicWorkaroundButton permissions={MIC_DENIED} />)

    await user.click(screen.getByRole('button', { name: 'Workaround permisos micrófono' }))

    expect(vi.mocked(resetMicrophonePermission)).toHaveBeenCalledTimes(1)
    expect(await screen.findByText('Workaround lanzado')).toBeInTheDocument()
    const description = screen.getByText(RESET_BOTH)
    expect(description).toHaveTextContent(/relanza Maurya/i)
    expect(description).toHaveTextContent(/inicia una grabación/i)
    expect(description).toHaveTextContent(/micrófono y de grabación de pantalla/i)
  })

  // SPEC-055-iter-2 · AC-05 (fallback)
  it('shows the manual-command fallback with both resets when Terminal could not be launched', async () => {
    vi.mocked(resetMicrophonePermission).mockResolvedValue(false)
    const user = userEvent.setup()
    render(<MicWorkaroundButton permissions={MIC_DENIED} />)

    await user.click(screen.getByRole('button', { name: 'Workaround permisos micrófono' }))

    expect(await screen.findByText('No se pudo lanzar el workaround')).toBeInTheDocument()
    expect(screen.getByText(/Ejecuta manualmente/)).toHaveTextContent(RESET_BOTH)
  })

  it('closes the instructions dialog with the confirm button', async () => {
    const user = userEvent.setup()
    render(<MicWorkaroundButton permissions={MIC_DENIED} />)

    await user.click(screen.getByRole('button', { name: 'Workaround permisos micrófono' }))
    expect(await screen.findByText('Workaround lanzado')).toBeInTheDocument()

    await user.click(screen.getByRole('button', { name: 'Entendido' }))

    expect(screen.queryByText('Workaround lanzado')).not.toBeInTheDocument()
  })
})
